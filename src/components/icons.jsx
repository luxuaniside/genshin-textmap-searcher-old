export function ChevronIcon({ direction = "down", size = 16 }) {
  const rotation = { down: 0, left: 90, up: 180, right: -90 }[direction];
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" style={{ transform: `rotate(${rotation}deg)` }}>
      <path d="m6 9 6 6 6-6" />
    </svg>
  );
}

